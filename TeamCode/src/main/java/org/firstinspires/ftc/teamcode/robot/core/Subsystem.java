package org.firstinspires.ftc.teamcode.robot.core;

/**
 * Общий контракт для всех самостоятельных механизмов робота.
 * <p>
 * Например:
 * - ходовая;
 * - лифт;
 * - захват;
 * - интейк;
 * - камера.
 */
public interface Subsystem {
  
  /**
   * Человекочитаемое название для телеметрии и ошибок.
   */
  String getName();
  
  /**
   * Первичная настройка подсистемы во время INIT.
   */
  void init();
  
  /**
   * Действия, выполняемые один раз после нажатия START.
   */
  void start();
  
  /**
   * Обновление подсистемы в каждом цикле OpMode.
   *
   * @param dtSeconds время после предыдущего цикла в секундах
   */
  void periodic(double dtSeconds);
  
  /**
   * Немедленная безопасная остановка подсистемы.
   */
  void stop();
  
  /**
   * Разрешено ли подсистеме сейчас работать.
   */
  boolean isEnabled();
  
  /**
   * Позволяет временно включить или отключить подсистему.
   */
  void setEnabled(boolean enabled);
  
  /**
   * Находится ли подсистема в аварийном состоянии.
   */
  boolean isFaulted();
  
  /**
   * Описание текущей ошибки или пустая строка.
   */
  String getFaultMessage();
  
}